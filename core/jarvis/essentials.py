"""brain/ESSENTIALS.md: one short, always-current digest of what anyone running JARVIS must know (T105).

Rebuilt by `bin/jarvis essentials` and by the `brain-sync` routine before each push, so the PC and the laptop
read the same page. Each section is built on its own and never stops the others; secrets are only ever named,
never printed.
"""

from __future__ import annotations

import re
from datetime import date

from . import paths, records

WHERE = [
    ("brain/ (git-ignored)", "memory/ Markdown, jarvis.db (tasks, decisions, money, journal index), journal/, work/"),
    ("brain/work/<area>/", "every deliverable and note, by task area; `bin/jarvis task path T<n>`"),
    ("brain/files/", "uploads, research, mentor captures; reels/ is a junction to C:\\JarvisMedia\\reels (PC only)"),
    ("brain/skills/", "private Blake playbooks; `bin/jarvis skills backup --restore` puts them in ~/.claude/skills"),
    ("brain/secrets/", "Telegram token, SIP keys, call key, dashboard token (never committed, synced separately)"),
    ("brain/tts/", "voice venvs and models: per machine, rebuilt by scripts/laptop-setup.ps1, never synced"),
    ("brain/backups/", "daily zips of db + memory + work + journal (local)"),
    ("OneDrive/JARVIS-laptop-transfer/", "lean brain + secrets zips the laptop pulls (`bin/jarvis sync`)"),
    ("repo (GitHub marley-gpt/jarvis, public)", "code, agents, skills; brain/ is never committed"),
    ("%LOCALAPPDATA%/JARVIS/role", "this machine's role: primary (PC) or standby (laptop), D69"),
]


def _section(title: str, build) -> list[str]:
    try:
        lines = build()
    except Exception as exc:  # one broken source must not blank the digest
        lines = [f"- (unavailable: {exc})"]
    return [f"\n## {title}"] + (lines or ["- none"])


def _claude_md_bullets(heading: str, limit: int = 10) -> list[str]:
    text = (paths.REPO_ROOT / "CLAUDE.md").read_text(encoding="utf-8")
    m = re.search(rf"^## {re.escape(heading)}.*?$(.*?)(?=^## )", text, re.S | re.M)
    if not m:
        return []
    out = []
    for line in m.group(1).splitlines():
        if line.startswith("- "):
            first = re.split(r"(?<=[.:])\s", line[2:].strip(), maxsplit=1)[0]
            out.append("- " + first.replace("**", "")[:170])
    return out[:limit]


def _memories(conn, where: str, args: tuple, limit: int) -> list[str]:
    rows = conn.execute(f"SELECT id, title FROM memory WHERE status = 'active' AND {where} ORDER BY updated DESC "
                        f"LIMIT ?", (*args, limit)).fetchall()
    return [f"- {r['id']} {r['title']}" for r in rows]


def _accounts(conn) -> list[str]:
    from . import sales_watch
    cfg = paths.config()
    sec = paths.home() / "secrets"
    mode = sales_watch.feed_mode()
    route = "read-only API tokens" if mode == "tokens" else "claude.ai connectors (Shopify, Meta ads)"
    sip = cfg.get("sip_provider") or {}
    sip = f"{sip.get('user')}@{sip.get('server')}" if isinstance(sip, dict) and sip else "not set"
    lines = [
        f"- Shopify store {cfg.get('store_url')}: read via {route}; live edits by JARVIS only (since 2026-10-27)",
        f"- Meta ad account: read via {route}; launches and budgets need approval",
        "- Telegram bot @jarvisclaudeecombot: " + ("paired (secrets/telegram.json)" if (sec / "telegram.json").exists()
                                                    else "NOT paired") + "; the bridge polls only on the primary",
        f"- Phone line: JARVIS's own SIP account {sip}" + (" (HA1 key present)" if (sec / "sip_provider_ha1").exists() else "") + "; call server on the primary",
        "- Claude: owner's claude.ai Max account; connectors (Shopify, Meta ads, Google Drive, Higgsfield, Docs) "
        "come with the login on any machine",
        "- OneDrive (owner's Microsoft account): carries the repo working copy and the lean brain sync",
        f"- This machine: {paths.machine_role()}",
    ]
    lines += _memories(conn, "title NOT LIKE 'Skill note%' AND (title LIKE '%Tailscale%' OR title LIKE '%phone line%')",
                       (), 5)
    return lines


def _money(conn) -> list[str]:
    from . import sales_watch
    today = date.today()
    mtd = records.money_report(conn, today.replace(day=1).isoformat(), today.isoformat())
    return [f"- {sales_watch.status_line(conn)}",
            f"- Month to date: income A${mtd['total_income']:.2f}, costs A${mtd['total_expenses']:.2f}, "
            f"profit A${mtd['profit']:.2f} (target to date A${mtd['target']:.2f})",
            f"- Paid AI/API this month: A${records.month_spend(conn):.2f} of A${paths.config()['monthly_ai_budget_aud']:.0f}"]


def build(conn) -> str:
    from . import brief
    out = [f"# JARVIS essentials ({paths.now()[:16].replace('T', ' ')}, written on the {paths.machine_role()})",
           "One page, regenerated by `bin/jarvis essentials` and the brain-sync routine. Details: "
           "`bin/jarvis mem get <id>`, `bin/jarvis brief`."]
    out += _section("Standing rules (CLAUDE.md)", lambda: _claude_md_bullets("Standing rules from the owner")
                    + _claude_md_bullets("Approval gates", 2))
    out += _section("Owner preferences and business facts (newest first)", lambda: _memories(
        conn, "provenance = 'user' AND category IN ('preferences', 'business')", (), 20))
    out += _section("Accounts and how each connects", lambda: _accounts(conn))
    out += _section("Open tasks", lambda: [brief.task_line(t)[:170] for t in
                                           records.task_list(conn, open_only=True, limit=12)])
    out += _section("Products and running tests", lambda: [
        f"- {p['slug']} ({p['stage']})" for p in conn.execute(
            "SELECT slug, stage FROM products WHERE stage NOT IN ('archived','failed') ORDER BY updated DESC LIMIT 8")
    ] + [f"- X{t['id']} {t['product']} [{t['status']}]: {t['hypothesis'][:100]}" for t in conn.execute(
        "SELECT * FROM tests WHERE status IN ('running','extended') ORDER BY id")])
    out += _section("Waiting for approval", lambda: [
        f"- A{a['id']} [{a['kind']}] {a['summary'][:120]}"
        for a in conn.execute("SELECT * FROM approvals WHERE status = 'pending' ORDER BY id")])
    out += _section("Money", lambda: _money(conn))
    out += _section("Key decisions (latest 10)", lambda: [
        f"- D{d['id']} {d['ts'][:10]} {d['decision'][:140]}"
        for d in conn.execute("SELECT * FROM decisions ORDER BY id DESC LIMIT 10")])
    out += _section("Where everything lives", lambda: [f"- {a}: {b}" for a, b in WHERE])
    return "\n".join(out) + "\n"


def write(conn):
    path = paths.home() / "ESSENTIALS.md"
    tmp = path.with_name("ESSENTIALS.md.tmp")
    tmp.write_text(build(conn), encoding="utf-8")
    tmp.replace(path)
    return path
